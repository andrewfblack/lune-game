// Existing episodes inherit their scenes; future episodes register in separate scripts.
// To add one, call registerEpisode({id, chapter, name, emoji, desc, steps, requiredFor}).
const EPISODES = LOCS.map(loc => ({ ...loc, steps:SCENES[loc.scene] }));
function registerCharacter(id, character) {
  if (!id || CHARACTERS[id] || !character || !character.name || !character.img) throw new Error(`Invalid/duplicate character: ${id}`);
  CHARACTERS[id] = character;
}
function registerEpisode(episode) {
  if (!episode || !episode.id || !episode.name || !Array.isArray(episode.steps) || EPISODES.some(e => e.id === episode.id)) throw new Error(`Invalid/duplicate episode: ${episode && episode.id}`);
  if (!CHAPTERS[episode.chapter]) throw new Error(`Unknown chapter for ${episode.id}`);
  const after = EPISODES.findIndex(e => e.id === episode.after);
  EPISODES.splice(after < 0 ? EPISODES.length : after + 1, 0, episode);
  if (episode.requiredFor) CHAPTERS[episode.requiredFor].requires.push(episode.id);
}
window.LUNE_CONTENT = { CHARACTERS, ITEMS, BLOOPERS, CHAPTERS, EPISODES, SCENES, registerCharacter, registerEpisode };
